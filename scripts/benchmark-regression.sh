#!/usr/bin/env bash
# RECON-W28 B-9 — automated per-wave regression diff against the frozen baseline.
#
# WHY THIS EXISTS
#   W22's acceptance criteria required every subsequent wave to be diffed against
#   w13-live.csv, so a wave could not silently trade one probe for another. That was
#   recorded as a criterion and then never automated: each wave ran the battery and
#   eyeballed a TOTAL line. A total cannot tell you WHICH probe changed, and a total
#   can stay flat while probes are swapped underneath it.
#
# WHAT IT DOES
#   Compares a fresh benchmark CSV against the frozen baseline, per probe_id, and
#   exits non-zero on any regression:
#     - a probe that passed before and fails now  -> REGRESSION (blocking)
#     - a probe that failed before and passes now -> IMPROVEMENT (reported)
#     - a probe that disappeared                    -> REGRESSION (blocking)
#     - a NEW probe that did not exist in baseline   -> reported, not blocking
#
#   Frozen battery: the comparison is keyed on probe_id, so adding probes cannot hide
#   a regression, and EvalBattery.java is never touched by this script.
#
# USAGE
#   bash scripts/benchmark-regression.sh [new-csv] [baseline-csv]
#   defaults: data/mind/benchmarks/latest.csv  and  data/mind/benchmarks/w13-live.csv
set -uo pipefail

NEW="${1:-data/mind/benchmarks/latest.csv}"
BASE="${2:-data/mind/benchmarks/w13-live.csv}"

if [ ! -f "$NEW" ]; then
  echo "ERROR: new benchmark '$NEW' not found."
  echo "       Produce one first:  bash scripts/w13-live-benchmark.sh $NEW"
  exit 2
fi
if [ ! -f "$BASE" ]; then
  echo "ERROR: baseline '$BASE' not found. The baseline is the frozen reference and"
  echo "       must exist; it is never regenerated by this script."
  exit 2
fi

python3 - "$NEW" "$BASE" <<'PY'
import csv, sys

new_path, base_path = sys.argv[1], sys.argv[2]

def load(path):
    out = {}
    with open(path, newline='', encoding='utf-8') as fh:
        for row in csv.DictReader(fh):
            pid = (row.get('probe_id') or '').strip()
            if not pid:
                continue
            out[pid] = {
                'passed': (row.get('passed') or '').strip().lower() == 'true',
                'category': (row.get('category') or '').strip(),
            }
    return out

try:
    new, base = load(new_path), load(base_path)
except Exception as exc:
    print(f"ERROR: could not read benchmark CSVs: {exc}")
    sys.exit(2)

regressions, improvements, added = [], [], []

for pid, b in base.items():
    if pid not in new:
        regressions.append((pid, b['category'], 'DISAPPEARED',
                            'probe present in baseline, absent from this run'))
        continue
    n = new[pid]
    if b['passed'] and not n['passed']:
        regressions.append((pid, b['category'], 'BROKEN',
                            'passed at baseline, fails now'))
    elif (not b['passed']) and n['passed']:
        improvements.append((pid, b['category']))

for pid in new:
    if pid not in base:
        added.append((pid, new[pid]['category']))

bp = sum(1 for v in base.values() if v['passed'])
np_ = sum(1 for v in new.values() if v['passed'])
bt, nt = len(base), len(new)

print('=' * 72)
print('BENCHMARK REGRESSION DIFF  (RECON-W28 B-9)')
print(f'  baseline : {base_path}  -> {bp}/{bt} passed')
print(f'  current  : {new_path}  -> {np_}/{nt} passed')
print('=' * 72)

if improvements:
    print(f'\nIMPROVEMENTS ({len(improvements)}) - expected to grow as waves land:')
    for pid, cat in sorted(improvements):
        print(f'  + {pid:<8} {cat}')

if added:
    print(f'\nNEW PROBES ({len(added)}) - not in the frozen baseline, informational:')
    for pid, cat in sorted(added):
        print(f'  ? {pid:<8} {cat}')

if regressions:
    print(f'\nREGRESSIONS ({len(regressions)}) - BLOCKING:')
    for pid, cat, kind, why in sorted(regressions):
        print(f'  ! {pid:<8} {cat:<18} {kind}: {why}')
    print('\nRESULT: FAIL — a probe that passed at baseline no longer passes.')
    print('Fix the cause. Do NOT relax the probe, and do not regenerate the baseline')
    print('to make this pass: the baseline is the frozen reference.')
    sys.exit(1)

print('\nRESULT: PASS — no probe regressed against the frozen baseline.')
sys.exit(0)
PY
